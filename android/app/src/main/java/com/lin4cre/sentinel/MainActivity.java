package com.lin4cre.sentinel;

import android.app.Activity;
import android.graphics.Typeface;
import android.graphics.drawable.GradientDrawable;
import android.os.Bundle;
import android.text.InputType;
import android.view.Gravity;
import android.view.View;
import android.view.WindowInsets;
import android.view.WindowManager;
import android.widget.Button;
import android.widget.EditText;
import android.widget.LinearLayout;
import android.widget.ScrollView;
import android.widget.TextView;

import org.json.JSONArray;
import org.json.JSONObject;

import java.util.Locale;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;

public final class MainActivity extends Activity {
    private static final int BG = 0xFF0A0F0E;
    private static final int PANEL = 0xFF111917;
    private static final int PANEL_RAISED = 0xFF18231D;
    private static final int TEXT = 0xFFE8EFEB;
    private static final int MUTED = 0xFFA1ADA5;
    private static final int ACCENT = 0xFFB7EF72;
    private static final int BORDER = 0xFF2B3932;

    private final ExecutorService executor = Executors.newSingleThreadExecutor();
    private ConfigStore configStore;
    private JSONObject config;
    private LinearLayout root;
    private LinearLayout content;
    private TextView status;

    @Override public void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        getWindow().setStatusBarColor(BG);
        getWindow().setNavigationBarColor(BG);
        getWindow().setSoftInputMode(WindowManager.LayoutParams.SOFT_INPUT_ADJUST_RESIZE);
        configStore = new ConfigStore(this);
        root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setBackgroundColor(BG);
        root.setPadding(dp(20), dp(12), dp(20), dp(16));
        root.setOnApplyWindowInsetsListener((view, insets) -> {
            int top = insets.getSystemWindowInsetTop();
            int bottom = insets.getSystemWindowInsetBottom();
            view.setPadding(dp(20), dp(12) + top, dp(20), dp(16) + bottom);
            return insets;
        });
        setContentView(root);

        try {
            config = configStore.load();
        } catch (Exception e) {
            configStore.clear();
            config = null;
            showMessage("Saved connection details could not be decrypted. They were removed; pair again.");
        }
        if (config == null) showConnectScreen(); else showHome();
    }

    @Override protected void onDestroy() {
        executor.shutdownNow();
        super.onDestroy();
    }

    private void showConnectScreen() {
        root.removeAllViews();
        root.addView(title("SENTINEL", 28, ACCENT));
        root.addView(text("Read-only Android companion", 16, TEXT, false), params(0, 8));
        root.addView(text("Connect to your SENTINEL mobile API over HTTPS. The core app and Windows host remain on your own machine.", 14, MUTED, false), params(0, 8));

        EditText url = edit("https://your-private-host.example", InputType.TYPE_CLASS_TEXT | InputType.TYPE_TEXT_VARIATION_URI, "HTTPS server URL");
        root.addView(url, params(0, 20));
        EditText token = edit("Paste the one-time token from python -m backend.mobile_pairing", InputType.TYPE_CLASS_TEXT | InputType.TYPE_TEXT_VARIATION_PASSWORD, "Bearer token");
        root.addView(token, params(0, 12));

        Button connect = button("Save securely and connect");
        root.addView(connect, params(0, 16));
        root.addView(text("Security: the token is encrypted with Android Keystore, sent only over HTTPS, and never logged. This companion is read-only. Do not expose the server over plain HTTP or directly to the public internet.", 13, MUTED, false), params(0, 14));
        connect.setOnClickListener(v -> {
            String tokenValue = token.getText().toString().trim();
            if (tokenValue.isEmpty() && config != null) tokenValue = config.optString("token", "");
            try {
                String base = ApiClient.validateBaseUrl(url.getText().toString());
                if (tokenValue.length() < 32 || tokenValue.length() > 256) throw new IllegalArgumentException("Enter the pairing token generated by the SENTINEL server.");
                JSONObject next = new JSONObject();
                next.put("baseUrl", base);
                next.put("token", tokenValue);
                configStore.save(base, tokenValue);
                config = next;
                showHome();
                refreshOverview();
            } catch (Exception e) {
                showMessage(e.getMessage() == null ? "Could not save the connection." : e.getMessage());
            }
        });
        if (config != null) {
            url.setText(config.optString("baseUrl", ""));
            token.setHint("Token saved securely. Leave blank to keep it, or enter a replacement.");
            Button forget = button("Forget saved connection");
            forget.setBackground(tint(PANEL_RAISED, 10, BORDER));
            root.addView(forget, params(0, 10));
            forget.setOnClickListener(v -> { configStore.clear(); config = null; showConnectScreen(); });
        }
    }

    private void showHome() {
        root.removeAllViews();
        LinearLayout header = new LinearLayout(this);
        header.setGravity(Gravity.CENTER_VERTICAL);
        header.setOrientation(LinearLayout.HORIZONTAL);
        TextView brand = title("SENTINEL", 24, ACCENT);
        header.addView(brand, new LinearLayout.LayoutParams(0, -2, 1));
        Button settings = smallButton("Connection");
        header.addView(settings);
        root.addView(header);
        settings.setOnClickListener(v -> showConnectScreen());
        root.addView(text("READ-ONLY COMPANION · " + config.optString("baseUrl"), 11, MUTED, false), params(0, 6));
        status = text("Connecting securely…", 13, MUTED, false);
        root.addView(status, params(0, 10));

        LinearLayout nav = new LinearLayout(this);
        nav.setOrientation(LinearLayout.HORIZONTAL);
        nav.setPadding(0, dp(10), 0, dp(6));
        Button overview = smallButton("Overview");
        Button programmes = smallButton("Programmes");
        Button approvals = smallButton("Approvals");
        nav.addView(overview, weightedButton());
        nav.addView(programmes, weightedButton());
        nav.addView(approvals, weightedButton());
        root.addView(nav);

        ScrollView scroll = new ScrollView(this);
        content = new LinearLayout(this);
        content.setOrientation(LinearLayout.VERTICAL);
        scroll.setFillViewport(true);
        scroll.addView(content);
        root.addView(scroll, new LinearLayout.LayoutParams(-1, 0, 1));
        overview.setOnClickListener(v -> refreshOverview());
        programmes.setOnClickListener(v -> loadProgrammes());
        approvals.setOnClickListener(v -> loadApprovals());
        refreshOverview();
    }

    private void refreshOverview() {
        contentStart("Loading dashboard…");
        apiCall(() -> new ApiClient(config.optString("baseUrl"), config.optString("token")).getObject("/overview"), result -> {
            status.setText("Connected · read-only · data not cached");
            content.removeAllViews();
            JSONObject counts = result.optJSONObject("counts");
            if (counts == null) counts = new JSONObject();
            content.addView(sectionTitle("Research overview"));
            addMetric("Programmes", counts.optInt("programmes"));
            addMetric("Pending approvals", counts.optInt("pending_approvals"));
            addMetric("Active approvals", counts.optInt("active_approvals"));
            addMetric("Findings · validated", counts.optInt("findings") + " · " + counts.optInt("validated_findings"));
            addMetric("Reports · accepted", counts.optInt("submitted_reports") + " · " + counts.optInt("accepted_reports"));
            JSONArray paid = result.optJSONArray("paid");
            if (paid != null && paid.length() > 0) {
                content.addView(sectionTitle("Actually paid (separate currencies)"), params(0, 12));
                for (int i = 0; i < paid.length(); i++) {
                    JSONObject item = paid.optJSONObject(i);
                    if (item != null) addMetric(item.optString("currency"), String.format(Locale.UK, "%.2f", item.optDouble("amount")));
                }
            }
            content.addView(text("The Android companion cannot create approvals, run tests, change settings, execute maintenance or submit reports.", 13, MUTED, false), params(0, 18));
        });
    }

    private void loadProgrammes() {
        contentStart("Loading programmes…");
        apiCall(() -> new ApiClient(config.optString("baseUrl"), config.optString("token")).getArray("/programmes?limit=50"), rows -> {
            status.setText("Connected · read-only · up to 50 recent programmes");
            content.removeAllViews();
            content.addView(sectionTitle("Programmes"));
            if (rows.length() == 0) content.addView(text("No programmes are recorded. Add one from the desktop application.", 15, MUTED, false), params(0, 10));
            for (int i = 0; i < rows.length(); i++) {
                JSONObject row = rows.optJSONObject(i);
                if (row == null) continue;
                LinearLayout card = card();
                card.addView(text(row.optString("name", "Unnamed programme"), 17, TEXT, true));
                card.addView(text(row.optString("platform") + " · " + row.optString("eligibility_status"), 13, ACCENT, false), params(0, 6));
                String reward = row.optString("currency", "") + " " + money(row.optDouble("reward_min")) + "–" + money(row.optDouble("reward_max"));
                card.addView(text("Maximum range: " + reward, 13, MUTED, false), params(0, 4));
                if (!row.isNull("score")) card.addView(text("Recorded score: " + money(row.optDouble("score")), 13, MUTED, false), params(0, 4));
                card.addView(text("Source checked: " + row.optString("source_checked_at", "not recorded"), 12, MUTED, false), params(0, 4));
                content.addView(card, params(0, 10));
            }
        });
    }

    private void loadApprovals() {
        contentStart("Loading approvals…");
        apiCall(() -> new ApiClient(config.optString("baseUrl"), config.optString("token")).getArray("/approvals?limit=50"), rows -> {
            status.setText("Connected · read-only · up to 50 approvals");
            content.removeAllViews();
            content.addView(sectionTitle("Scope approvals"));
            if (rows.length() == 0) content.addView(text("No approval records yet.", 15, MUTED, false), params(0, 10));
            for (int i = 0; i < rows.length(); i++) {
                JSONObject row = rows.optJSONObject(i);
                if (row == null) continue;
                LinearLayout card = card();
                card.addView(text(row.optString("programme_name", "Programme"), 17, TEXT, true));
                card.addView(text(row.optString("status", "unknown").toUpperCase(Locale.UK) + " · expires " + row.optString("expires_at"), 13, ACCENT, false), params(0, 6));
                card.addView(text("Assets: " + join(row.optJSONArray("assets")), 13, MUTED, false), params(0, 4));
                card.addView(text("Methods: " + join(row.optJSONArray("methods")) + " · limit " + row.optInt("rate_limit") + "/min", 13, MUTED, false), params(0, 4));
                content.addView(card, params(0, 10));
            }
        });
    }

    private interface Request { Object run() throws Exception; }
    private interface Success { void accept(Object result); }

    private void apiCall(Request request, Success success) {
        if (config == null) { showConnectScreen(); return; }
        executor.execute(() -> {
            try {
                Object result = request.run();
                runOnUiThread(() -> success.accept(result));
            } catch (Exception e) {
                runOnUiThread(() -> {
                    content.removeAllViews();
                    status.setText("Connection failed · no changes were made");
                    content.addView(sectionTitle("SENTINEL unavailable"));
                    content.addView(text(e.getMessage() == null ? "Could not reach the companion API." : e.getMessage(), 15, MUTED, false), params(0, 8));
                    Button retry = button("Retry");
                    content.addView(retry, params(0, 12));
                    retry.setOnClickListener(v -> refreshOverview());
                });
            }
        });
    }

    private void contentStart(String message) {
        if (content == null) return;
        status.setText(message);
        content.removeAllViews();
        content.addView(text(message, 15, MUTED, false), params(0, 10));
    }

    private void addMetric(String label, int value) { addMetric(label, String.valueOf(value)); }
    private void addMetric(String label, String value) {
        LinearLayout row = new LinearLayout(this);
        row.setOrientation(LinearLayout.HORIZONTAL);
        row.setGravity(Gravity.CENTER_VERTICAL);
        row.setPadding(dp(14), dp(12), dp(14), dp(12));
        row.setBackground(tint(PANEL, 10, BORDER));
        TextView key = text(label, 14, MUTED, false);
        row.addView(key, new LinearLayout.LayoutParams(0, -2, 1));
        row.addView(text(value, 18, TEXT, true));
        content.addView(row, params(0, 8));
    }

    private LinearLayout card() {
        LinearLayout box = new LinearLayout(this);
        box.setOrientation(LinearLayout.VERTICAL);
        box.setPadding(dp(14), dp(14), dp(14), dp(14));
        box.setBackground(tint(PANEL, 12, BORDER));
        return box;
    }

    private void showMessage(String message) {
        if (root == null) return;
        android.widget.Toast.makeText(this, message, android.widget.Toast.LENGTH_LONG).show();
    }

    private TextView sectionTitle(String value) { return title(value, 20, TEXT); }
    private TextView title(String value, int size, int color) {
        TextView view = text(value, size, color, true);
        return view;
    }
    private TextView text(String value, int size, int color, boolean bold) {
        TextView view = new TextView(this);
        view.setText(value);
        view.setTextSize(size);
        view.setTextColor(color);
        view.setGravity(Gravity.CENTER_VERTICAL);
        if (bold) view.setTypeface(Typeface.DEFAULT, Typeface.BOLD);
        return view;
    }

    private EditText edit(String hint, int inputType, String label) {
        EditText view = new EditText(this);
        view.setSingleLine(true);
        view.setTextSize(15);
        view.setTextColor(TEXT);
        view.setHintTextColor(MUTED);
        view.setHint(hint);
        view.setInputType(inputType);
        view.setContentDescription(label);
        view.setPadding(dp(12), dp(12), dp(12), dp(12));
        view.setBackground(tint(PANEL, 10, BORDER));
        return view;
    }

    private Button button(String label) {
        Button view = new Button(this);
        view.setText(label);
        view.setTextColor(BG);
        view.setTextSize(14);
        view.setAllCaps(false);
        view.setTypeface(Typeface.DEFAULT, Typeface.BOLD);
        view.setBackground(tint(ACCENT, 10, ACCENT));
        view.setPadding(dp(14), dp(8), dp(14), dp(8));
        return view;
    }

    private Button smallButton(String label) {
        Button view = new Button(this);
        view.setText(label);
        view.setTextColor(TEXT);
        view.setTextSize(12);
        view.setAllCaps(false);
        view.setMinHeight(dp(42));
        view.setBackground(tint(PANEL_RAISED, 9, BORDER));
        view.setPadding(dp(4), dp(4), dp(4), dp(4));
        return view;
    }

    private LinearLayout.LayoutParams weightedButton() {
        LinearLayout.LayoutParams lp = new LinearLayout.LayoutParams(0, -2, 1);
        lp.setMargins(dp(2), 0, dp(2), 0);
        return lp;
    }

    private LinearLayout.LayoutParams params(int width, int topDp) {
        LinearLayout.LayoutParams lp = new LinearLayout.LayoutParams(width == 0 ? -1 : width, -2);
        lp.topMargin = dp(topDp);
        return lp;
    }

    private GradientDrawable tint(int color, int radiusDp, int stroke) {
        GradientDrawable bg = new GradientDrawable();
        bg.setColor(color);
        bg.setCornerRadius(dp(radiusDp));
        bg.setStroke(dp(1), stroke);
        return bg;
    }

    private int dp(int value) { return Math.round(value * getResources().getDisplayMetrics().density); }
    private String money(double value) { return String.format(Locale.UK, "%.2f", value); }
    private String join(JSONArray values) {
        if (values == null || values.length() == 0) return "none recorded";
        StringBuilder result = new StringBuilder();
        for (int i = 0; i < values.length(); i++) {
            if (i > 0) result.append(", ");
            result.append(values.optString(i));
        }
        return result.toString();
    }
}
